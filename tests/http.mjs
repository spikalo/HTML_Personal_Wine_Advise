import assert from 'node:assert/strict';
const base = process.argv[2] || 'http://127.0.0.1:8080/';
const response = await fetch(base);
assert.equal(response.status, 200);
const html = await response.text();
assert.equal((html.match(/type="number"/g) || []).length, 28);
const cookie = response.headers.get('set-cookie').split(';')[0];
const csrf = html.match(/name="csrf" value="([a-f0-9]+)"/)[1];
assert.ok(response.headers.get('content-security-policy').includes("frame-ancestors 'none'"));
const keys = ['acidity','body','sweetness','citrus','apple','tropical','stone','melon','pear','nuts','redfruit','flowers','honey','herbs'];
const valid = new URLSearchParams({csrf, type: 'Red'});
for (const key of keys) for (let i = 0; i < 2; i++) valid.set(`answers[${key}][${i}]`, '5');
let checks = 0;
async function post(label, body, status, currentCookie = cookie) {
  const r = await fetch(new URL('index.php', base), {method: 'POST', headers: {Cookie: currentCookie}, body});
  const text = await r.text();
  assert.equal(r.status, status, label);
  assert.ok(!text.includes('Fatal error'), label);
  console.log(`PASS ${label}: ${r.status}`);
  checks++;
  return text;
}
const result = await post('complete form', valid, 200);
assert.equal((result.match(/wine-card/g) || []).length, 12);
await post('missing answers', new URLSearchParams({csrf}), 422);
await post('missing CSRF', new URLSearchParams(), 403);
let bad = new URLSearchParams(valid);
bad.set('answers[body][0]', '11');
await post('out of range', bad, 422);
await post('malformed collection', new URLSearchParams({csrf, answers: 'bad'}), 422);
bad = new URLSearchParams(valid);
bad.set('type', '<script>alert(1)</script>');
assert.ok(!(await post('invalid type / XSS', bad, 422)).includes('<script>alert(1)</script>'));
const other = await fetch(base);
const otherCookie = other.headers.get('set-cookie').split(';')[0];
await post('cross-session CSRF rejected', valid, 403, otherCookie);
bad = new URLSearchParams({csrf});
for (const key of keys) bad.set(`skip[${key}]`, '1');
await post('all dimensions skipped', bad, 422);
bad = new URLSearchParams(valid);
bad.set('padding', 'a'.repeat(33000));
await post('oversized body', bad, 413);
assert.equal((await fetch(base, {method: 'PUT'})).status, 405);
console.log(`PASS unsupported method: 405\n${checks + 1} HTTP checks passed.`);
